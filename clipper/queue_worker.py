DB_PATH = os.path.join(os.path.dirname(__file__), 'clips_db.json')
CHANNELS_DB = os.path.join(os.path.dirname(os.path.dirname(__file__)), 'channels_db.json')
_db_lock = lock_for(DB_PATH)

def read_db():
    data = read_json(DB_PATH, [])
    if not isinstance(data, list):
        raise ValueError('Format database job tidak valid.')
    return data

def write_db(data):
    write_json(DB_PATH, data)

def update_db(mutate):
    return update_json(DB_PATH, [], mutate)


def cancel_jobs(job_id=None, yt_id=None):
    return cancel_jobs_in(DB_PATH, job_id=job_id, yt_id=yt_id)


def check_cancelled(job_id):
    try:
        check_job(DB_PATH, job_id)
        return False
    except JobCancelled:
        return True


def ensure_active(job_id):
    return check_job(DB_PATH, job_id)


def update_job(job_id, **fields):
    return update_job_in(DB_PATH, job_id, fields)

def upload_to_youtube(video_path, job_data):
    try:
        from googleapiclient.discovery import build
        from google.oauth2.credentials import Credentials
        from googleapiclient.http import MediaFileUpload
        from zoneinfo import ZoneInfo
        
        target_id = job_data.get('options', {}).get('targetChannelId')
        
        with open(CHANNELS_DB, 'r') as f:
            channels = json.load(f)
            
        channel = next((c for c in channels if c.get('yt_id') == target_id), None)
        if not channel: raise Exception("Channel Target tidak ditemukan di database!")
        
        creds_str = channel.get('creds_list', [channel.get('creds_json')])[0]
        creds = Credentials.from_authorized_user_info(json.loads(creds_str))
        youtube = build('youtube', 'v3', credentials=creds)
        
        title = f"Viral Moment #{job_data['batch_index']} #shorts"
        body = {
            'snippet': {'title': title, 'description': 'Auto-generated by KeiBot Clipper Pro', 'categoryId': '24'},
            'status': {'privacyStatus': 'public'}
        }
        
        if job_data.get('publish_date'):
            sch_obj = datetime.strptime(job_data['publish_date'], "%Y-%m-%dT%H:%M")
            sch_obj += timedelta(days=(job_data['batch_index'] - 1))
            wib = ZoneInfo("Asia/Jakarta")
            import datetime as dt
            sch_utc = sch_obj.replace(tzinfo=wib).astimezone(dt.timezone.utc)
            if sch_obj.replace(tzinfo=wib) > datetime.now(wib):
                body['status']['privacyStatus'] = 'private'
                body['status']['publishAt'] = sch_utc.strftime("%Y-%m-%dT%H:%M:%S.000Z")

        media = MediaFileUpload(video_path, resumable=True)
        req = youtube.videos().insert(part=','.join(body.keys()), body=body, media_body=media)
        
        response = None
        while response is None:
            ensure_active(job_data['id'])
            status, response = req.next_chunk()
            if status:
                update_job(job_data['id'], progress=int(status.progress()*100), stage=f"Mengunggah ke YT... {int(status.progress()*100)}%")
                
        return response.get('id')
    except Exception as e:
        raise Exception(f"Gagal Upload YT: {str(e)}")

def upload_to_facebook(video_path, job_data):
    import requests
    from zoneinfo import ZoneInfo
    
    opts = job_data.get('options', {})
    page_id = opts.get('fb_page_id')
    if not page_id: raise Exception("Facebook Page belum dipilih di menu Dropdown!")
    
    fb_pages_file = os.path.join(os.path.dirname(os.path.dirname(__file__)), 'facebook_pages.json')
    if not os.path.exists(fb_pages_file): raise Exception("Database FB Pages tidak ditemukan!")
    
    with open(fb_pages_file, 'r') as f:
        fb_pages = json.load(f)
        
    page_data = next((p for p in fb_pages if p['page_id'] == page_id), None)
    if not page_data: raise Exception("Akses Token Facebook Page tidak ditemukan!")
    
    page_token = page_data['access_token']
    file_size = os.path.getsize(video_path)
    caption = f"Viral Moment #{job_data['batch_index']} #Reels #Viral"
    
    # 1. TAHAP START
    start_url = f"https://graph.facebook.com/v19.0/{page_id}/video_reels"
    start_res = requests.post(start_url, data={"upload_phase": "start", "access_token": page_token}, timeout=30).json()
    if "error" in start_res: raise Exception(f"FB Start Error: {start_res['error'].get('message')}")
    
    video_id = start_res.get("video_id")
    upload_url = start_res.get("upload_url")
    
    # 2. TAHAP TRANSFER FILE
    with open(video_path, "rb") as vf: video_bytes = vf.read()
    up_headers = {"Authorization": f"OAuth {page_token}", "offset": "0", "file_size": str(file_size)}
    up_res = requests.post(upload_url, headers=up_headers, data=video_bytes, timeout=300).json()
    if "error" in up_res: raise Exception(f"FB Upload Error: {up_res['error'].get('message')}")
    
    # 3. TAHAP FINISH & SCHEDULING
    finish_params = {
        "access_token": page_token, "video_id": video_id,
        "upload_phase": "finish", "video_state": "PUBLISHED", "description": caption
    }
    
    if job_data.get('publish_date'):
        try:
            sch_obj = datetime.strptime(job_data['publish_date'], "%Y-%m-%dT%H:%M")
            sch_obj += timedelta(days=(job_data['batch_index'] - 1))
            wib = ZoneInfo("Asia/Jakarta")
            sch_aware = sch_obj.replace(tzinfo=wib)
            import datetime as dt
            now_aware = dt.datetime.now(wib)
            if (sch_aware - now_aware).total_seconds() >= 900: # Syarat API FB: Minimal 15 mnt ke depan
                finish_params["video_state"] = "SCHEDULED"
                finish_params["scheduled_publish_time"] = int(sch_aware.timestamp())
        except: pass
        
    fin_res = requests.post(start_url, data=finish_params, timeout=60).json()
    if "error" in fin_res: raise Exception(f"FB Finish Error: {fin_res['error'].get('message')}")
    
    return video_id

def clipper_worker_loop():
    recover_jobs(DB_PATH)
    print("🚀 [Clipper Pro Worker] Background thread dimulai...")
    while True:
        try:
            jobs = read_db()
            job_to_run = next((j for j in jobs if j.get('status') == 'queued'), None)

            if job_to_run:
                job_id = job_to_run['id']
                opts = job_to_run.get('options', {})
                batch_idx = job_to_run.get('batch_index', 1)
                total_batch = job_to_run.get('total_batch', 1)
                
                update_job(job_id, status='processing', stage='Menunggu slot CPU/RAM kosong...')
                acquire_resource(worker_name="Clipper Worker", cancelled=lambda: check_cancelled(job_id))
                
                temp_files = []
                source_path = None
                try:
                    # 1. DOWNLOAD
                    update_job(job_id, status='downloading', progress=20, stage='Mengunduh video sumber...')
                    source_path = download_source(url=job_to_run['url'], video_id=job_id.split('_')[0], resolution="1080p")
                    
                    # 2. DETEKSI VIRAL MOMENT (AI)
                    update_job(job_id, status='clipping', progress=40, stage='Menganalisis momen viral (AI)...')
                    moments = get_viral_moments(source_path, count=total_batch, duration_sec=40)
                    my_moment = moments[batch_idx - 1] if batch_idx <= len(moments) else moments[0]
                    
                    start_time = my_moment['start']
                    duration = my_moment['duration']
                    
                    # --- PERSIAPAN AUDIO BGM DILAKUKAN LEBIH AWAL ---
                    bgm_file = opts.get('bgmFile', 'none')
                    audio_mode = opts.get('audioMode', 'bgm')
                    asset_id = opts.get('assetChannelId', '')
                    bgm_path = None
                    
                    if bgm_file != 'none' and asset_id:
                        bgm_path = os.path.join(os.path.dirname(os.path.dirname(__file__)), 'uploads', asset_id, bgm_file)
                    
                    # 3. POTONG AUDIO & GENERATE LIRIK (Auto-Switch Sumber Suara)
                    srt_path = None
                    if opts.get('lyricStyle') != 'none':
                        update_job(job_id, status='clipping', progress=60, stage='Generate Lirik via AI...')
                        audio_clip = f"{source_path}_{job_id}_audio.mp3"
                        temp_files.append(audio_clip)
                        
                        # LOGIKA PINTAR: Pilih suara apa yang akan didengarkan oleh AI
                        if audio_mode == "replace" and bgm_path and os.path.exists(bgm_path):
                            # Jika Mute Mode: Potong lagu BGM sesuai durasi video dan kirim ke AI
                            subprocess.run(['/usr/bin/ffmpeg', '-y', '-stream_loop', '-1', '-i', bgm_path, '-t', str(duration), '-q:a', '0', '-map', 'a', audio_clip], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
                        else:
                            # Jika BGM Mode: Potong suara asli dari video dan kirim ke AI
                            subprocess.run(['/usr/bin/ffmpeg', '-y', '-ss', str(start_time), '-t', str(duration), '-i', source_path, '-q:a', '0', '-map', 'a', audio_clip], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
                        
                        # Rotasi global lintas semua provider.
                        # ai_provider lama tidak lagi membatasi penggunaan token.
                        srt_path = generate_lyrics_srt(
                            audio_clip,
                            job_to_run.get('api_keys', []),
                            provider='auto'
                        )
                        if srt_path: temp_files.append(srt_path)

                    # 4. RENDER FINAL (Crop + Visualizer + Lirik + Audio Mix)
                    update_job(job_id, status='encoding', progress=80, stage='Rendering Efek & Filter FFmpeg...')
                    output_name = f"clip_{job_id}.mp4"
                    output_path = os.path.join(os.path.dirname(os.path.dirname(__file__)), 'static', output_name)
                    
                    ensure_active(job_id)
                    process_clip_pro(
                        source_path=source_path,
                        output_path=output_path,
                        start_time=start_time,
                        duration=duration,
                        crop_mode=opts.get('cropMode', 'center'),
                        lyric_style=opts.get('lyricStyle', 'none'),
                        srt_path=srt_path,
                        use_visualizer=opts.get('useVisualizer', False),
                        bgm_path=bgm_path,
                        audio_mode=audio_mode,
                        custom_font=opts.get('customFont', ''),
                        vis_params=opts.get('visParams', {}),
                        cancel_callback=lambda: check_cancelled(job_id)
                    )
                    
                    ensure_active(job_id)
                    # 5. DESTINASI OUTPUT
                    dest = opts.get('outputDest', 'youtube')
                    target_id = opts.get('targetChannelId', '')
                    
                    if dest == 'youtube':
                        if not target_id:
                            raise Exception("Channel Target YouTube belum dipilih di menu Dropdown!")
                        update_job(job_id, status='encoding', progress=95, stage='Proses Upload ke YouTube...')
                        yt_id = upload_to_youtube(output_path, job_to_run)
                        final_msg = f"Selesai & Dijadwalkan! (YT ID: {yt_id})"
                    elif dest == 'facebook':
                        update_job(job_id, status='encoding', progress=95, stage='Proses Upload ke FB Reels...')
                        fb_vid = upload_to_facebook(output_path, job_to_run)
                        final_msg = f"Selesai & Dijadwalkan! (FB ID: {fb_vid})"
                    else:
                        raise Exception("Destinasi output tidak valid! Pilih antara YouTube atau Facebook.")

                    update_job(job_id, status='done', progress=100, stage=final_msg, output_file=output_name)
                    print(f"✅ [Clipper Worker] Job {job_id} selesai.")
                    
                except Exception as e:
                    print(f"❌ [Clipper Worker] Error job {job_id}: {e}")
                    update_job(job_id, status='error', stage=f'Error: {str(e)}')
                
                finally:
                    for tf in temp_files:
                        if os.path.exists(tf): 
                            try: os.remove(tf)
                            except: pass
                    
                    if batch_idx == total_batch and source_path:
                        if os.path.exists(source_path):
                            try: os.remove(source_path)
                            except Exception as e: pass

                    release_resource(worker_name="Clipper Worker")
                    
        except Exception as main_e:
            print(f"⚠️ [Clipper Worker] Fatal error: {main_e}")
            
        time.sleep(2)

if os.environ.get('KEIBOT_START_WORKERS', '1') == '1':
    threading.Thread(target=clipper_worker_loop, daemon=True).start()